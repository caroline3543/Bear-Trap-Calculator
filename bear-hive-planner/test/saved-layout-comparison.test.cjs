'use strict';
const assert=require('node:assert/strict'),H=require('../dist/world-map.js');
const before=H.migrate(H.emptyPlan());
before.slots=[{id:'a',x:3,y:4,w:2,h:2,trap:1},{id:'b',x:6,y:7,w:2,h:2,trap:1}];
const after=JSON.parse(JSON.stringify(before));
after.mapOrigin={x:before.mapOrigin.x+10,y:before.mapOrigin.y+5};
after.slots=[{...before.slots[0],x:before.slots[0].x-10,y:before.slots[0].y-5},{...before.slots[1],x:before.slots[1].x-9,y:before.slots[1].y-5},{id:'c',x:0,y:0,w:2,h:2,trap:2}];
after.settings.hqX=601;after.settings.hqY=602;
const original=JSON.stringify(before),current=JSON.stringify(after);
const diff=H.compareSavedLayouts(before,after);
assert.equal(diff.unchanged.length,1);
assert.equal(diff.moved.length,1);
assert.equal(diff.added.length,1);
assert.equal(diff.removed.length,0);
assert.equal(diff.moved[0].to.x-diff.moved[0].from.x,1);
assert.equal(diff.structures[0].name,'HQ');
assert.equal(JSON.stringify(before),original);
assert.equal(JSON.stringify(after),current);
console.log('Saved-layout world-coordinate comparison tests passed');
