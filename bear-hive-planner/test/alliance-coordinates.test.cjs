'use strict';
const assert=require('node:assert/strict');
const H=require('../dist/world-map.js');
const plan=H.migrate(H.emptyPlan());
plan.settings.hqX=612;plan.settings.hqY=617;plan.settings.nodeX=620;plan.settings.nodeY=622;
const first=H.allianceMarkers(plan);
assert.equal(first.length,2);
assert.deepEqual(first.map(x=>[x.name,x.worldX,x.worldY]),[['HQ',612,617],['Node',620,622]]);
const restored=H.validate(JSON.parse(JSON.stringify(plan)));
assert.deepEqual(H.allianceMarkers(restored).map(x=>[x.worldX,x.worldY]),[[612,617],[620,622]]);
const origin=H.worldOrigin(restored);
assert.equal(first[0].x+origin.x,612);
assert.equal(first[1].y+origin.y,622);
restored.settings.hqX=null;restored.settings.hqY=null;
assert.equal(H.allianceMarkers(restored).length,1);

const modePlan=H.migrate(H.emptyPlan());
const originalX=modePlan.settings.anchorX;
const terrain=H.switchMapMode(modePlan,'terrain');
const updated=H.changeMapReference(terrain,{anchorX:originalX+1}).state;
const plain=H.switchMapMode(updated,'plain');
assert.equal(plain.settings.anchorX,originalX+1,'map mode must not restore old BT coordinates');
assert.equal(H.switchMapMode(plain,'terrain').settings.anchorX,originalX+1);
const obstaclePlan=H.migrate(H.emptyPlan());
const baseline=H.suggestTrapPositions(obstaclePlan,1,{radius:12,limit:100});
const free=baseline.find(p=>p.distance>0);
assert(free,'Fixture needs an available trap candidate');
obstaclePlan.settings.hqX=free.x;obstaclePlan.settings.hqY=free.y;
const occupied=H.allianceMarkers(obstaclePlan)[0];
assert(H.overlap({x:free.x-H.worldOrigin(obstaclePlan).x,y:free.y-H.worldOrigin(obstaclePlan).y,w:3,h:3},occupied));
const alternatives=H.suggestTrapPositions(obstaclePlan,1,{radius:12,limit:200});
assert(!alternatives.some(p=>p.x===free.x&&p.y===free.y),'Candidates must exclude HQ footprint');
const shifted=H.previewTrapShift(obstaclePlan,1,free.x,free.y);
assert.equal(shifted.valid,false,'HQ collision must invalidate a trap shift');
const adapted=H.previewAdaptiveReflow(obstaclePlan,1,free.x,free.y);
assert.equal(adapted.valid,false,'HQ collision must invalidate adaptive reflow');
assert.throws(()=>H.applyAdaptiveReflow(obstaclePlan,1,free.x,free.y));
console.log('Alliance coordinate marker persistence and relocation collision tests passed');
