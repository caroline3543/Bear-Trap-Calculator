const assert=require('node:assert/strict'),H=require('../dist/world-map.js');
let s=H.migrate(H.emptyPlan());
assert.equal(s.mapMode,'plain');
assert.equal(s.traps.length,2);
assert.equal(H.worldFeatures(s,{x:-30,y:-30,w:60,h:60}).length,0);
s=H.applyBulk(s,H.reviewBulk(s,'[LUN] Alpha, 123456, f'),()=> 'alpha',1);
const plain=JSON.parse(JSON.stringify(s));
s=H.switchMapMode(s,'terrain');
assert.equal(s.traps.length,2,'BT1 and BT2 should appear on first terrain visit');
assert.equal(s.slots.length,0,'Separate city drafts remain independent');
for(const id of [1,2]){
 const t=s.traps.find(t=>t.id===id),o=H.worldOrigin(s);
 assert(t,'Missing terrain trap '+id);
 assert.equal(t.x+o.x,id===1?s.settings.anchorX:s.settings.anchor2X);
 assert.equal(t.y+o.y,id===1?s.settings.anchorY:s.settings.anchor2Y);
}
assert(H.worldFeatures(s,{x:-30,y:-30,w:60,h:60}).length>0);
const terrain=JSON.parse(JSON.stringify(s));
s=H.switchMapMode(s,'plain');
assert.deepEqual(s.traps,plain.traps);
assert.equal(s.members.length,1);
s=H.switchMapMode(s,'terrain');
assert.deepEqual(s.traps,terrain.traps);
const legacy=JSON.parse(JSON.stringify(s));
legacy.mapDrafts.terrain.traps=[];
legacy.mapMode='plain';
const restored=H.switchMapMode(legacy,'terrain');
assert.equal(restored.traps.length,2,'Old empty terrain drafts must restore saved BT coordinates');
H.validate(restored);
console.log('PASS: terrain traps align with settings on first visit, restore legacy drafts, and survive roundtrips.');
