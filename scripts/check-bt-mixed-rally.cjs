const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const os = require('node:os');
const deps = process.env.BT_TEST_DEPS ? require('node:module').createRequire(path.join(process.env.BT_TEST_DEPS,'package.json')) : require;
(async () => {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(),'bt-fc-form-'));
  const repo = path.resolve(__dirname,'..');
  const { JSDOM } = deps('jsdom');
  const dom = new JSDOM('<div id="root"></div>',{url:'https://test.example'});
  Object.assign(global,{window:dom.window,document:dom.window.document,localStorage:dom.window.localStorage,HTMLElement:dom.window.HTMLElement,IS_REACT_ACT_ENVIRONMENT:true});
  await deps('esbuild').build({entryPoints:[path.join(repo,'src/bear/BearLab.jsx')],outfile:path.join(tmp,'form.cjs'),bundle:true,platform:'node',format:'cjs',external:['react'],loader:{'.css':'empty','.webp':'dataurl'},logLevel:'silent'});
  const React = deps('react'); const {act} = React;
  const root = deps('react-dom/client').createRoot(document.getElementById('root'));
  const Form = require(path.join(tmp,'form.cjs')).default;
  let accountId='test';
  const inventory={t11:{infantry:0,lancer:0,marksman:100000},t10:{infantry:100000,lancer:100000,marksman:100000},t9:{infantry:0,lancer:0,marksman:0}};
  let actualRally={marksman:{t11:50000,t10:50000}};
  let tiers = [{fc:5,level:10},{fc:4,level:10},{fc:6,level:10}], applied=[];
  const render = () => root.render(React.createElement(Form,{key:accountId,accountId,accountName:'Main',leaderCapacity:160010,troopTiers:tiers,inventory,actualRally,onApplyLeader:counts=>applied.push(counts)}));
  const input = (label,value) => {const el=document.querySelector(`input[aria-label="${label}"]`);Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype,'value').set.call(el,value);el.dispatchEvent(new window.Event('input',{bubbles:true}));};
  try {
    await act(async()=>render());
    await act(async()=>document.querySelector('.bl-launch').click());
    await act(async()=>{input('Infantry hero','Hector');input('Lancer hero','Mia');input('Marksman hero','Gwen');});
    assert.equal(document.querySelectorAll('.bl-compare').length,3);
    assert.equal(document.querySelector('.bl-comparison-result'),null,'Closed comparison does not add fields');
    await act(async()=>document.querySelector('form').dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true})));
    const section=document.querySelector('.bl-compare');
    await act(async()=>{section.open=true;section.dispatchEvent(new window.Event('toggle'));});
    await act(async()=>{input('Alternative Infantry hero','Jeronimo');input('Alternative Infantry stars','5');input('Alternative Infantry widget','10');input('Alternative Infantry skill level','5');});
    assert.equal(document.querySelector('.bl-comparison-result'),null,'Missing gear must block comparison');
    await act(async()=>[...section.querySelectorAll('button')].find(b=>b.textContent.includes('gear readings')).click());
    assert.ok(document.querySelector('.bl-comparison-result'));
    assert.ok(document.querySelector('.bl-ideal-result'),'Editing an unused alternative leaves active squad intact');
    assert.equal(section.querySelectorAll('.bl-score-card').length,2);
    const winner=section.querySelector('.bl-score-best > span').textContent;
    const use=section.querySelector('.bl-comparison-result button');
    assert.ok(use.textContent.includes(winner));
    await act(async()=>use.click());
    assert.equal(document.querySelector('input[aria-label="Infantry hero"]').value,winner);
    assert.equal(applied.length,2);
    const score=()=>[...document.querySelectorAll('.bl-model-score')].find(e=>e.textContent.startsWith('Current rally boost:')).querySelector('strong').textContent;
    const beforeScore=score();
    actualRally={marksman:{t11:0,t10:100000}};
    await act(async()=>render());
    assert.ok(Number(score())<Number(beforeScore),'Replacing Helios with T10 lowers the live score at the same class count');
    assert.ok(document.querySelector('.bl-tier-mix').textContent.includes('FC'));
    assert.ok(document.body.textContent.includes('Inventory-adjusted optimal boost'));

    assert.equal(applied[1].reduce((a,b)=>a+b),160010);
    const saved=JSON.parse(localStorage.getItem('bearLeader:v2:test')).profile;
    assert.equal(saved.starters[0],winner);
    assert.equal(saved.alternatives[0].name,winner==='Jeronimo'?'Hector':'Jeronimo');
    accountId='farm';
    await act(async()=>render());
    await act(async()=>document.querySelector('.bl-launch').click());
    assert.equal(document.querySelector('input[aria-label="Infantry hero"]').value,'','Farm does not inherit Main heroes');
    accountId='test';
    await act(async()=>render());
    await act(async()=>document.querySelector('.bl-launch').click());
    assert.equal(document.querySelector('input[aria-label="Infantry hero"]').value,winner,'Saved hero restored on return');
    await act(async()=>root.unmount());
    console.log('Mixed rally UI passed: inventory-aware hero comparison, real tier mix, live manual tier score changes and account-isolated saved heroes.');
  } finally { dom.window.close();fs.rmSync(tmp,{recursive:true,force:true}); }
})().catch(error=>{console.error(error);process.exitCode=1;});
